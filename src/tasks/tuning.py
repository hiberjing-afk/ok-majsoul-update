#: 本次要主动点亮的自动开关. 「鸣」= 自动拒绝鸣牌, 点着它雀魂不画吃碰杠
#: 面板, 决策层就没机会判断该不该碰 —— 默认不点.
AUTO_TOGGLES_ON = ("和", "鸣", "拔")


def auto_toggles_on(has_yaku: bool) -> tuple[str, ...]:
    """本次要主动点亮的自动开关.

    默认只点「和」「拔」; 只有 `AUTO_DECLINE_MELD=True` 且没有役牌对子时
    才点「鸣」, 把没役的鸣牌机会交给游戏自动拒.
    """
    if AUTO_DECLINE_MELD and not has_yaku:
        return AUTO_TOGGLES_ON
    return tuple(n for n in AUTO_TOGGLES_ON if n != "鸣")


def auto_toggles_off() -> tuple[str, ...]:
    """必须保持关闭的自动开关: 「切」会替我们打出摸到的牌."""
    return ("切",)


