def auto_toggles_on(has_yaku: bool) -> tuple[str, ...]:
    """要点亮的左上自动开关(见 _ensure_auto_toggles), **按手**动态决定.

    「鸣」开关的含义是**自动拒绝鸣牌**:
    - 本手手里有役牌对子(白/发/中/场风东) -> 不点「鸣」, 让碰的机会弹出来,
      配合 MELD_POLICY="peng" 真正执行碰(用户 2026-10-08 拍板的方案:
      开局看手牌, 有役对全碰, 没役对就自动不鸣);
    - 没有役对 -> 点「鸣」自动拒绝 —— 反正 decide_turn 也不会碰, 自动拒绝
      省掉"弹机会->点跳过"的动作, 更拟人.
    「和」(自动和了)与「拔」(自动拔北)不受鸣牌影响, 恒开.
    """
    if has_yaku:
        return tuple(n for n in AUTO_TOGGLES_ON if n != "鸣")
    return AUTO_TOGGLES_ON

