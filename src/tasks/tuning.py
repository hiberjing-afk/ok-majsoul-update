"""内部调参 -- **不进配置系统**的代码常量.

**为什么不是配置项**(2026-10-07 用户决定, 参照 ok-nte 的做法):
任务卡片展开后渲染的是 `default_config`里的**每一项**, 而 ok-script 没有
"隐藏但保留配置"的官方机制(`hidden` 只为派生字段设计, 见
`src/widget_types.py`). 把二十几项阈值 / 延迟 / 比例塞进 `default_config`
的结果是: 卡片上一片密密麻麻的控件, 而这些参数正常用根本不该碰.

所以分工是:
  - **界面上只留用户真正常用的**: 人数 / 时长 / 连打局数 / 存档截图/
    稳健出牌(见两处 `_DEFAULT_CONFIG`);
  - **其余全部搬到这里**, 改法是直接改本文件的常量.

对照 ok-nte(`src/tasks/DailyTask.py`, 已下载核对): 它 `default_config`
只有 8 项, 模块级常量 16 个 -- 内部调参一律不进配置系统. 它的做法是
把参数从配置里**拿出去**, 而不是想办法隐藏. 本模块就是照这个思路.

**改这些值之前先看每条的注释** -- 里面记了实跑踩过的坑和阈值来历,
不是随手填的数字. 改完跑 `tools/check_gui_startup.py` 与单元测试.
"""

